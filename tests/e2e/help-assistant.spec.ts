import { expect, test } from '@playwright/test';
import { projectWorkspaceFixture } from './fixtures/projectWorkspace';

for (const [width, height, theme] of [[1440, 1000, 'light'], [1280, 800, 'light'], [960, 540, 'light'], [1440, 1000, 'dark']] as const) {
  test(`Help conversation at ${width}x${height} ${theme} keeps sources and controls accessible`, async ({ page }, info) => {
    test.setTimeout(90000);
    await page.setViewportSize({ width, height });
    await page.addInitScript(() => {
      Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: async () => { throw new DOMException('Microphone permission denied. You can still type.', 'NotAllowedError'); } } });
    });
    const fixture = await projectWorkspaceFixture(page, 'head', false, { landingOnly: true, theme });
    const submitted: Record<string, unknown>[] = [];
    await page.route(/\/controlpanelEflow\/api\/help-assistant\//, async route => {
      const operation = new URL(route.request().url()).pathname.split('/').at(-1);
      if (operation === 'projects') return route.fulfill({ json: { projects: [{ id: fixture.project, title: 'QA Community outreach', status: 'active' }] } });
      if (operation === 'status') return route.fulfill({ json: { speechInstalled: true, readOnly: true, model: 'qwen3.5:2b' } });
      if (operation === 'chat') {
        const body = route.request().postDataJSON(); submitted.push(body);
        return route.fulfill({ json: {
          replyId: 'reply', answer: body.question.includes('planets') ? 'I can help with eFlow workflows and project records you can access.' : 'QA registration is awaiting review. Recorded lead: Alex. This identifies a follow-up, not proof of personal fault.',
          sources: body.question.includes('planets') ? [] : [{ id: 'task:one', title: 'QA registration', text: 'QA registration is awaiting review. Recorded lead: Alex.', kind: 'task', projectId: fixture.project }],
          notice: 'AI can make mistakes.', model: 'qwen3.5:2b', grounded: true, observedAt: Date.now() / 1000, knowledgeVersion: '2026-10-22',
        } });
      }
      return route.fulfill({ status: 503, json: { detail: 'No real speech is generated by this isolated UI fixture.' } });
    });
    await page.getByRole('button', { name: 'Open help', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Talk to eFlow AI', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toBeVisible();
    await expect(dialog.getByText('Lightweight AI can make mistakes. Verify important details in eFlow.')).toBeVisible();
    await dialog.getByLabel('Ask about', { exact: true }).selectOption(fixture.project);
    await dialog.getByRole('button', { name: 'Dictate question', exact: true }).click();
    await expect(dialog.getByRole('alert')).toContainText('Microphone permission denied');
    await dialog.getByRole('textbox', { name: 'Ask eFlow AI', exact: true }).fill('Why is this project waiting?');
    await dialog.getByRole('button', { name: 'Send question', exact: true }).click();
    await expect(dialog.locator('.eflow-help-message--assistant')).toContainText('awaiting review');
    await dialog.getByText('1 source', { exact: true }).click();
    await expect(dialog.locator('strong').filter({ hasText: 'QA registration' }).first()).toBeVisible();
    await expect(dialog.getByRole('button', { name: 'Send question', exact: true })).toBeVisible();
    const bounds = await dialog.boundingBox();
    expect(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y + bounds.height <= height + 1).toBe(true);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`help-${width}-${height}-${theme}.png`) });
    expect(submitted[0].projectId).toBe(fixture.project);
    expect(submitted[0].mode).toBe('chat');
    expect(submitted[0]).not.toHaveProperty('context');
    await dialog.getByRole('button', { name: 'eFlow Live', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'eFlow Live', exact: true })).toBeVisible();
    await expect(dialog.getByRole('region', { name: 'eFlow Live conversation' })).toBeVisible();
    await expect(dialog.getByRole('button', { name: 'Resume eFlow Live' })).toBeVisible();
    const liveBounds = await dialog.boundingBox();
    expect(liveBounds && liveBounds.x >= 0 && liveBounds.y >= 0 && liveBounds.x + liveBounds.width <= width + 1 && liveBounds.y + liveBounds.height <= height + 1).toBe(true);
    await page.screenshot({ path: info.outputPath(`eflow-live-${width}-${height}-${theme}.png`) });
    expect(liveBounds!.width).toBeGreaterThanOrEqual(Math.min(1200, width - 48));
    // Reproduce a long answer at desktop/zoom-equivalent viewport sizes. Only
    // the main area scrolls; the answer must not acquire a second scrollbar.
    await dialog.locator('.eflow-live__caption p').evaluate(element => {
      element.textContent = 'A submitted request waits for its required decision and release scheduling. A request, reservation or approval message is not proof that cash was already released. '.repeat(5);
    });
    const main = dialog.locator('.eflow-live__main');
    const caption = dialog.locator('.eflow-live__caption p');
    expect(await caption.evaluate(element => element.scrollHeight <= element.clientHeight + 1)).toBe(true);
    expect(await caption.evaluate(element => getComputedStyle(element).overflowY)).toBe('visible');
    await main.evaluate(element => { element.scrollTop = element.scrollHeight; });
    const captionBounds = await caption.boundingBox();
    const footerBounds = await dialog.locator('.eflow-live__bottom').boundingBox();
    expect(captionBounds!.y + captionBounds!.height).toBeLessThanOrEqual(footerBounds!.y + 1);
    await expect(dialog.getByRole('button', { name: 'End eFlow Live' })).toBeVisible();
    await page.screenshot({ path: info.outputPath(`eflow-live-long-answer-${width}-${height}-${theme}.png`) });
    await dialog.getByRole('button', { name: 'End eFlow Live' }).click();
    await expect(dialog.getByRole('textbox', { name: 'Ask eFlow AI' })).toBeFocused();
    await dialog.press('Escape'); await expect(dialog).not.toBeVisible();
    await expect(page.getByRole('button', { name: 'Open help', exact: true })).toBeFocused();
  });
}

test('Dictation fills an editable draft; eFlow Live sends spoken turns and releases the mic on End', async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addInitScript(() => {
    const state = window as unknown as { qaVoiceNode: { port: { onmessage: (event: { data: Float32Array }) => void } }; qaMicStops: number };
    state.qaMicStops = 0;
    const playback = window as unknown as { qaPlayed: number; qaAudio: { onended: (() => void) | null } };
    playback.qaPlayed = 0;
    Object.defineProperty(window, 'Audio', { configurable: true, value: class {
      onended: (() => void) | null = null; onerror = null; src = '';
      constructor() { playback.qaAudio = this; }
      pause() {} async play() { playback.qaPlayed++; }
    } });
    const connection = { connect() { return this; }, disconnect() {} };
    Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: async () => {
      const track = { stop() { state.qaMicStops++; }, addEventListener() {}, removeEventListener() {} };
      return { getTracks: () => [track], getAudioTracks: () => [track] };
    } } });
    Object.defineProperty(window, 'AudioContext', { configurable: true, value: class {
      sampleRate = 16000; state = 'running'; destination = {}; audioWorklet = { addModule: async () => {} };
      async resume() {} async close() { this.state = 'closed'; }
      createGain() { return { ...connection, gain: { value: 0 } }; }
      createMediaStreamSource() { return connection; }
    } });
    Object.defineProperty(window, 'AudioWorkletNode', { configurable: true, value: class {
      port = { onmessage: (_event: { data: Float32Array }) => {} };
      constructor() { state.qaVoiceNode = this; }
      connect() { return connection; } disconnect() {}
    } });
  });
  await projectWorkspaceFixture(page, 'head', false, { landingOnly: true });
  let transcriptions = 0;
  let releaseLivePreview!: () => void;
  const heldLivePreview = new Promise<void>(resolve => { releaseLivePreview = resolve; });
  const questions: string[] = [];
  const modes: string[] = [];
  let finishFirst!: () => void, finishSecond!: () => void;
  const firstSpeech = new Promise<void>(resolve => { finishFirst = resolve; });
  const secondSpeech = new Promise<void>(resolve => { finishSecond = resolve; });
  const requestedParts: number[] = [];

  await page.route(/\/controlpanelEflow\/api\/help-assistant\//, async route => {
    const operation = new URL(route.request().url()).pathname.split('/').at(-1);
    if (operation === 'projects') return route.fulfill({ json: { projects: [] } });
    if (operation === 'status') return route.fulfill({ json: { speechInstalled: true, readOnly: true } });
    if (operation === 'transcribe') { transcriptions++; if (transcriptions === 3) await heldLivePreview; return route.fulfill({ json: { text: transcriptions === 1 ? 'How do I request' : 'How do I request petty cash?' } }); }
    if (operation === 'chat') {
      questions.push(route.request().postDataJSON().question);
      modes.push(route.request().postDataJSON().mode);
      return route.fulfill({ json: { replyId: `reply-${questions.length}`, answer: 'Open the task and choose Request petty cash.', sources: [], notice: 'AI can make mistakes.', model: 'qwen3.5:2b', grounded: true } });
    }

    if (operation === 'speech') {
      const part = route.request().postDataJSON().part; requestedParts.push(part);
      await (part === 0 ? firstSpeech : secondSpeech);
      return route.fulfill({ json: { audio: 'd2F2', mimeType: 'audio/wav', part, parts: 2 } });
    }
    return route.fulfill({ status: 503, json: { detail: 'Audio playback is outside this synthetic microphone test.' } });
  });
  await page.getByRole('button', { name: 'Open help', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Talk to eFlow AI', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Dictate question' }).click();
  await expect(dialog.getByRole('button', { name: 'Finish dictation' })).toBeVisible();
  const feed = async (silence: boolean, frames?: number) => page.evaluate(({ quiet, frames }) => {
    const state = window as unknown as { qaVoiceNode: { port: { onmessage: (event: { data: Float32Array }) => void } } };
    for (let index = 0; index < (frames || (quiet ? 70 : 10)); index++) state.qaVoiceNode.port.onmessage({ data: new Float32Array(512).fill(quiet ? 0 : .004) });
  }, { quiet: silence, frames });
  const draft = dialog.getByRole('textbox', { name: 'Ask eFlow AI' });
  await feed(false, 65);
  await expect(draft).toHaveValue('How do I request');
  await expect(dialog.getByRole('button', { name: 'Finish dictation' })).toBeVisible();
  expect(questions).toHaveLength(0);
  await expect(dialog.getByRole('meter', { name: 'Microphone input level' })).toHaveAttribute('aria-valuenow', '16');
  await page.screenshot({ path: info.outputPath('dictation-progressive-desktop.png') });
  await dialog.getByRole('button', { name: 'Finish dictation' }).click();
  await expect(draft).toHaveValue('How do I request petty cash?');
  await expect(draft).toBeFocused();
  expect(questions).toHaveLength(0);
  expect(transcriptions).toBe(2);
  await draft.fill('How do I request petty cash for supplies?');
  await dialog.getByRole('button', { name: 'Send question' }).click();
  await expect(dialog.locator('.eflow-help-message--assistant')).toBeVisible();
  expect(questions).toEqual(['How do I request petty cash for supplies?']);
  await dialog.getByRole('button', { name: 'eFlow Live', exact: true }).click();
  await expect(dialog.getByRole('status')).toHaveText('Listening');
  await page.screenshot({ path: info.outputPath('eflow-live-listening-desktop.png') });
  await dialog.getByRole('button', { name: 'Mute spoken replies' }).click();
  await feed(false); await feed(true, 59);
  await expect(dialog.getByText('Finishing your turn…', { exact: true })).toBeVisible();
  expect(questions).toHaveLength(1);
  await feed(true, 4);
  await expect(dialog.getByRole('status')).toContainText('Understanding your words');
  await expect(dialog.getByRole('meter', { name: 'Microphone input level' })).toHaveAttribute('aria-valuenow', '0');
  expect(questions).toHaveLength(1);
  expect(transcriptions).toBe(3);
  await page.screenshot({ path: info.outputPath('live-local-silence-before-asr.png') });
  releaseLivePreview();
  await expect.poll(() => questions.length).toBe(2);
  expect(modes).toEqual(['chat', 'live']);
  await expect(dialog.getByRole('status')).toHaveText('Listening');
  await dialog.getByRole('button', { name: 'Show transcript' }).click();
  await expect(dialog.getByRole('log', { name: 'Live transcript' })).toContainText('How do I request petty cash?');
  await dialog.getByRole('button', { name: 'Hide transcript' }).click();

  // Pause during synthesis keeps that turn alive, and the first part plays
  // before the final part is delivered. No physical microphone/model is mocked as verified.
  await dialog.getByRole('button', { name: 'Enable spoken replies' }).click();
  await feed(false); await feed(true);
  await expect.poll(() => requestedParts.length).toBe(1);
  await dialog.getByRole('button', { name: 'Pause eFlow Live' }).click();
  await expect(dialog.getByRole('button', { name: 'Resume eFlow Live' })).toBeVisible();
  finishFirst();
  await expect.poll(() => page.evaluate(() => (window as unknown as { qaPlayed: number }).qaPlayed)).toBe(1);
  await expect.poll(() => requestedParts).toEqual([0, 1]);
  await page.screenshot({ path: info.outputPath('live-paused-speech-continues.png') });
  finishSecond();
  await page.evaluate(() => (window as unknown as { qaAudio: { onended: (() => void) | null } }).qaAudio.onended?.());
  await expect.poll(() => page.evaluate(() => (window as unknown as { qaPlayed: number }).qaPlayed)).toBe(2);
  await page.evaluate(() => (window as unknown as { qaAudio: { onended: (() => void) | null } }).qaAudio.onended?.());
  await expect(dialog.getByRole('status')).toHaveText('Conversation paused');
  await dialog.getByRole('button', { name: 'Resume eFlow Live' }).click();
  await expect(dialog.getByRole('status')).toHaveText('Listening');
  const stoppedBefore = await page.evaluate(() => (window as unknown as { qaMicStops: number }).qaMicStops);
  await dialog.getByRole('button', { name: 'End eFlow Live' }).click();
  await expect(draft).toBeFocused();
  expect(await page.evaluate(() => (window as unknown as { qaMicStops: number }).qaMicStops)).toBeGreaterThan(stoppedBefore);
});

