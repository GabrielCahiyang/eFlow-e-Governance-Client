import {expect,test} from '@playwright/test';
import {projectWorkspaceFixture} from './fixtures/projectWorkspace';
import {nestedWorkStaffingFixture} from './fixtures/nestedWorkStaffing';

test('subtask staffing prioritizes task people and searches eligible specialists',async({page},info)=>{
 test.setTimeout(90_000);
 await page.setViewportSize({width:1440,height:1000});
 const records=await projectWorkspaceFixture(page,'head',false,{landingOnly:true});
 const specialist='00000000-0000-4000-8000-000000000088';
 const colleague='00000000-0000-4000-8000-000000000089';
 records.profiles.push({...records.profile,id:specialist,full_name:'Ada Specialist'},{...records.profile,id:colleague,full_name:'Task Contributor'});
 records.officeMembers.push({user_id:specialist},{user_id:colleague});
 records.tasks[0].team_member_ids=[records.id,colleague];
 const fixture=await nestedWorkStaffingFixture(page,records);
 await page.getByRole('navigation',{name:'Global navigation'}).getByRole('button',{name:'My Work',exact:true}).click();
 await page.getByRole('navigation',{name:'My Work destinations'}).getByRole('button',{name:'Work I lead',exact:true}).click();
 await page.locator('[data-personal-task]').filter({hasText:'Prepare community assessment'}).click();
 const task=page.getByRole('dialog',{name:'Task details: Prepare community assessment',exact:true});
 await task.getByRole('tab',{name:'Work',exact:true}).click();
 await task.getByRole('button',{name:'Actions for Gather supporting evidence',exact:true}).click();
 await page.getByRole('menuitem',{name:'Choose people',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Subtask Lead and contributors',exact:true});
 const lead=dialog.getByRole('combobox',{name:'Appointed Lead'});
 await expect(lead.locator('optgroup')).toHaveCount(1);
 await expect(lead.locator('optgroup').first()).toHaveAttribute('label','On this task');
 await expect(lead.locator('option',{hasText:'Ada Specialist'})).toHaveCount(0);
 const contributors=dialog.getByRole('group',{name:/^Contributors \(/});
 await expect(contributors.getByRole('group',{name:'On this task'}).getByRole('button',{name:'Add contributor Task Contributor'})).toBeVisible();
 await expect(contributors.getByRole('group',{name:'Other eligible members'})).toHaveCount(0);
 await expect(dialog.getByRole('button',{name:'Add contributor Ada Specialist'})).toHaveCount(0);
 await dialog.getByRole('searchbox',{name:'Find people'}).fill('contributor');
 await dialog.getByRole('button',{name:'Add contributor Task Contributor'}).click();
 await expect(dialog.getByRole('button',{name:'Remove contributor Task Contributor'})).toBeVisible();
 expect(fixture.commands).toHaveLength(0);
 expect(fixture.snapshot().root.people).toEqual([records.id,colleague]);
 await page.screenshot({path:info.outputPath('subtask-assignment-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await expect(dialog.getByRole('button',{name:'Save changes'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('subtask-assignment-narrow.png')});
});
