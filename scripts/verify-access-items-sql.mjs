/** Phase 2 isolated PostgreSQL rehearsal; no .env/live connections. Uses the
 * same disposable PGlite runtime as verify-admin-unification-sql.mjs. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../tmp/phase1-sql-runtime/node_modules/@electric-sql/pglite/dist/index.js';
const db = await PGlite.create();
const read = async (path) => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const sql = (name) => read(`supabase/migrations/${name}.sql`);
const extract = (source, name) => {
  const start = source.indexOf(`create or replace function public.${name}(`);
  assert.ok(start >= 0, name); return source.slice(start, source.indexOf('$$;', start) + 3);
};
let assertions = 0;
const check = async (expression) => { assert.equal((await db.query(`select (${expression}) ok`)).rows[0].ok, true, expression); assertions++; };
const denied = async (statement, pattern) => { await assert.rejects(db.exec(statement), pattern); assertions++; };
const uid = (n) => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
const identity = (n) => db.query("select set_config('request.jwt.claim.sub', $1, false)", [n ? uid(n) : '']);
const org = '10000000-0000-0000-0000-000000000002';
try {
  const fixture = await read('tests/sql/admin-unification-fixture.sql');
  const split = fixture.indexOf('alter table public.profiles enable');
  await db.exec(fixture.slice(0, split));
  await db.exec(await read('tests/sql/access-items-fixture.sql'));
  const core = await sql('20260712000000_core_workflow');
  for (const name of ['auth_role', 'auth_org_path', 'org_in_my_subtree', 'is_super_admin', 'is_project_member']) await db.exec(extract(core, name));
  const access = await sql('20260819000000_sir_gerson_access_control');
  for (const name of ['has_permission', 'can_access_org']) await db.exec(extract(access, name));
  await db.exec(fixture.slice(split));
  await db.exec(await sql('20260928000004_revocable_admin_role'));
  await db.exec(await sql('20260928000005_admin_leadership_profile_edits'));
  const leadership = await sql('20260814000000_assistant_head_review_routing');
  await db.exec(extract(leadership, 'set_organization_leadership'));
  const portfolios = await sql('20260819000005_proposal_portfolios_and_unique_leadership');
  for (const name of ['guard_profile_leadership_integrity', 'can_create_scoped_work']) await db.exec(extract(portfolios, name));
  const runtime = await sql('20260821000003_collaboration_runtime');
  for (const name of ['can_see_project', 'can_manage_project', 'can_see_task', 'can_manage_task']) await db.exec(extract(runtime, name));
  await db.exec(extract(await sql('20260822000008_department_budget_and_petty_cash'), 'is_department_budget_approver'));
  const accounting = await sql('20260919000000_phase04_phase05_accounting');
  for (const name of ['is_department_accounting_staff', 'can_manage_department_accounting']) await db.exec(extract(accounting, name));
  // A representative SECURITY DEFINER operation exercises the inserted gate;
  // existing financial amounts/reviewer rules retain their separate coverage.
  await db.exec(`create function public.record_accounting_petty_cash_release(p_org_id uuid) returns void language plpgsql security definer as $$ begin
    if not public.can_manage_department_accounting(p_org_id, auth.uid()) then raise exception 'Accounting scope denied'; end if;
    insert into audit_events(actor_id,action) values(auth.uid(),'fixture.accounting.release'); end $$;`);
  await db.exec(await sql('20261003000000_unify_admin_identity'));
  for (let iteration = 0; iteration < 2; iteration++) {
    await db.exec(await sql('20261003000001_access_items_and_employee_status'));
    await db.exec(await sql('20261003000002_dynamic_item_capabilities'));
  }
  await check('(select count(*) from employee_statuses) = 3');
  await check('(select count(*) from access_items where employee_status_id is not null) = 0');
  await check("(select count(*) from profiles where role = 'admin') = 3");
  await identity(1);
  await db.exec('set role authenticated');
  await db.exec("insert into employee_statuses(name) values ('Contractual')");
  await denied("insert into employee_statuses(name) values ('  contractual  ')", /employee_status_name_unique/);
  const { rows: [status] } = await db.query("select id from employee_statuses where name = 'Contractual'");
  const { rows: [item] } = await db.query("insert into access_items(title, role, employee_status_id) values ('Admin', 'Head', $1) returning *", [status.id]);
  await check(`'${item.permission_key}' like 'item_%'`);
  await denied(`update access_items set permission_key = 'admin' where id = '${item.id}'`, /immutable/);
  await denied(`insert into access_items(title,role,employee_status_id) values (' admin ', 'head', '${status.id}')`, /access_item_description_unique/);
  await denied(`delete from employee_statuses where id = '${status.id}'`, /foreign key/);
  await denied("update access_items set is_active = false where permission_key = 'admin'", /must remain active/);
  await identity(3);
  await denied("insert into employee_statuses(name) values ('Escalation')", /Only Admin|row-level security/);
  await denied(`insert into access_items(title, role, employee_status_id) values ('Bypass', 'Admin', '${status.id}')`, /Only Admin|row-level security/);
  await denied(`update profiles set role = '${item.permission_key}' where id = '${uid(4)}'`, /Only.*Admin/);
  await db.exec('reset role');
  await identity(null);
  await denied(`select finalize_managed_user('${uid(3)}', '${uid(6)}', '{"email":"test@example.test","full_name":"No", "role":"dept_head", "org_id":"${org}"}')`, /Admin access/);
  await db.exec('set role authenticated');
  await denied(`select finalize_managed_user('${uid(1)}', '${uid(6)}', '{}')`, /permission denied/);
  await db.exec('reset role');
  const create = async (n, role, target = org) => db.query('select finalize_managed_user($1, $2, $3::jsonb)', [uid(1), uid(n), JSON.stringify({role, org_id: target, email: `${n}@example.test`, full_name: `User ${n}`})]);
  await denied(`select finalize_managed_user('${uid(1)}','${uid(6)}','{"role":"dept_head","org_id":"${org}"}')`, /Employee Status/);
  await identity(1);
  await db.exec("update access_items set employee_status_id=(select id from employee_statuses where name='Regular/Permanent') where permission_key in ('admin','dept_head','assistant_head','employee','accounting_staff')");
  await identity(null);
  await create(6, 'dept_head');
  await create(7, 'assistant_head');
  await check(`(select head_user_id = '${uid(6)}' and assistant_head_user_id = '${uid(7)}' from organizations where id = '${org}')`);
  await check(`(select role = 'dept_head' and employee_id = 'UNASSIGNED-${uid(6)}' from profiles where id = '${uid(6)}')`);
  await create(6, 'dept_head');
  await check(`(select count(*) from audit_events where action = 'user.created_in_item' and entity_id = '${uid(6)}') = 1`);
  await assert.rejects(create(8, 'dept_head'), /already has an appointed/); assertions++;
  await check(`not exists(select 1 from profiles where id = '${uid(8)}')`);
  await denied(`insert into profiles(id, role, org_id) values('${uid(8)}', 'assistant_head', '${org}')`, /leadership slot/);
  await create(9, item.permission_key);
  await check(`not is_admin('${uid(9)}') and not has_permission('${uid(9)}', 'users.manage')`);
  await check(`not can_create_scoped_work('${org}', '${uid(9)}')`);
  await check(`not can_see_project('20000000-0000-0000-0000-000000000001', '${uid(9)}')`);
  await identity(9);
  await db.exec('set role authenticated');
  await check('(select count(*) from projects) = 0');
  await db.exec('reset role');
  await identity(1);
  await denied(`update access_items set is_active=false where id='${item.id}'`, /Reassign active users/);
  await db.exec(`insert into role_permissions(role,permission,allowed) values('${item.permission_key}','navigation.projects',true),('${item.permission_key}','projects.create',true)`);
  await check(`can_create_scoped_work('${org}', '${uid(9)}')`);
  await check(`can_see_project('20000000-0000-0000-0000-000000000001', '${uid(9)}')`);
  await identity(9);
  await db.exec('set role authenticated');
  await check('(select count(*) from projects) = 1');
  await db.exec('reset role');
  await identity(1);
  await check(`not can_create_scoped_work('10000000-0000-0000-0000-000000000001', '${uid(9)}')`);
  await identity(9);
  await denied(`select record_accounting_petty_cash_release('${org}')`, /accounting capability/);
  await identity(1);
  await db.exec(`insert into role_permissions(role,permission,allowed) values('${item.permission_key}','navigation.accounting_journal',true)`);
  await check(`can_manage_department_accounting('${org}', '${uid(9)}')`);
  await identity(9);
  await denied(`select record_accounting_petty_cash_release('${org}')`, /accounting capability/);
  await identity(1);
  await db.exec(`insert into role_permissions(role,permission,allowed) values('${item.permission_key}','accounting.release_cash',true)`);
  await check(`can_manage_department_accounting('${org}', '${uid(9)}') and not is_department_budget_approver('${org}', '${uid(9)}')`);
  await identity(9);
  await db.exec(`select record_accounting_petty_cash_release('${org}')`);
  await denied("select record_accounting_petty_cash_release('10000000-0000-0000-0000-000000000001')", /scope denied/);
  await identity(1);
  await db.exec(`update access_items set title='Analyst', role='Reviewer' where id='${item.id}'`);
  await check(`(select role='${item.permission_key}' from profiles where id='${uid(9)}') and has_permission('${uid(9)}','projects.create')`);
  await identity(9);
  await denied(`insert into tasks(id,title) values(gen_random_uuid(),'Forbidden')`, /tasks.assign/);
  await db.exec(`insert into projects(id,title,owner_id,org_id) values(gen_random_uuid(),'Allowed','${uid(9)}','${org}')`);
  await denied("delete from projects where title='Allowed'", /projects.delete/);
  await identity(1);
  await db.exec(`insert into user_permission_overrides values('${uid(9)}','projects.create',false,null)`);
  await check(`not has_permission('${uid(9)}','projects.create') and not can_create_scoped_work('${org}','${uid(9)}')`);
  await db.exec(`insert into user_permission_overrides values('${uid(9)}','accounting.release_cash',false,null)`);
  await identity(9);
  await denied(`select record_accounting_petty_cash_release('${org}')`, /accounting capability/);
  await identity(1);
  await db.exec(`update profiles set is_active=false where id='${uid(9)}'; update access_items set is_active=false where id='${item.id}'`);
  await check(`auth_role('${uid(9)}') is null and not has_permission('${uid(9)}','navigation.projects')`);
  await denied(`update profiles set is_active=true where id='${uid(9)}'`, /active Item/);
  await denied(`delete from access_items where id='${item.id}'`, /assigned to users|foreign key/);
  await db.exec(`update employee_statuses set is_active=false where id='${status.id}'`);
  await denied(`insert into access_items(title,role,employee_status_id) values('New','New','${status.id}')`, /active Employee Status/);
  await db.exec("insert into employee_statuses(name) values('Unused'); delete from employee_statuses where name='Unused'");
  const {rows:[unused]} = await db.query("insert into access_items(title,role,employee_status_id) select 'Unused Item', 'Unused', id from employee_statuses where name='Casual' returning id,permission_key");
  await db.exec(`insert into role_permissions(role,permission,allowed) values('${unused.permission_key}','navigation.tasks',true); delete from access_items where id='${unused.id}'`);
  await check(`not exists(select 1 from role_permissions where role='${unused.permission_key}') and exists(select 1 from audit_events where entity_id='${unused.id}' and action='catalogue.access_items.delete')`);
  await denied("delete from access_items where permission_key='executive'", /System Items/);
  await check("exists(select 1 from audit_events where action='catalogue.employee_statuses.delete')");
  console.log(`Phase 2 SQL rehearsal passed (${assertions} assertions; both migrations applied twice).`);
} catch (error) {
  console.error(error.message); if (error.where) console.error(error.where); process.exitCode = 1;
} finally { await db.close(); }
