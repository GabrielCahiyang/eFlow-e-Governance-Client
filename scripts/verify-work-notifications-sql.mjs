import assert from 'node:assert/strict';
import { notificationDatabase } from '../tests/sql/helpers/notificationDatabase.mjs';
import { migrationSource } from '../tests/sql/helpers/financialCompatibilityDatabase.mjs';
import { financeId as id } from '../tests/sql/helpers/financialScenario.mjs';

const { db, actor, value, project, root, node, office } = await notificationDatabase();
let assertions = 0;
const check = (actual, expected, label) => { assert.deepEqual(actual, expected, label); assertions++; };
try {
  await db.exec('reset role');
  const before = await value('select count(*) from notifications');
  await db.exec(await migrationSource('20261117010000_relevant_work_notifications.sql'));
  check(await value('select count(*) from notifications'), before, 'No backfill or notification storm at installation');
  await actor(5);
  await db.query("update tasks set due_date='2030-12-30' where id=$1", [root]);
  await db.exec('reset role');
  const notices = (await db.query("select * from notifications where task_id=$1 and title='Task schedule changed' order by user_id", [root])).rows;
  check(notices.map(row => row.user_id), [2, 6, 9].map(id), 'Only current Head, Project Lead and contributor receive schedule changes');
  check(notices.every(row => row.actor_id === id(5) && row.reason.includes('2030-12-31 → 2030-12-30') && row.project_id === project), true, 'Who, before/after and project context are retained');
  await actor(5);
  await db.query("update tasks set due_date='2030-12-30',percent_complete=percent_complete where id=$1", [root]);
  await db.exec('reset role');
  check(await value("select count(*) from notifications where task_id=$1 and title='Task schedule changed'", [root]), 3, 'No-op saves do not notify');
  await actor(3);
  check(await value("select count(*) from notifications where task_id=$1 and title='Task schedule changed'", [root]), 0, 'Foreign Office cannot read a recipient alert');
  await actor(9);
  check(await value("select count(*) from notifications where task_id=$1 and title='Task schedule changed'", [root]), 1, 'Recipient can read their own notification');
  await assert.rejects(db.query("select eflow_notify.emit_work($1,null,$2,'Forged','forged')", [root, id(9)]), /permission denied/); assertions++;
  await actor(5);
  const proposal = await value('select m7_propose_work($1,$2,$3,$4,$5::jsonb)', [root, null, id(970), 'progress', JSON.stringify({ progress: 10, note: 'Venue booking confirmed' })]).catch(() => null);
  check(proposal, null, 'A Lead cannot bypass their own progress authority using contributor submission');
  await actor(9);
  const terms = JSON.stringify({ progress: 20, note: 'Called the venue to confirm access' });
  const submitted = await value('select m7_propose_work($1,$2,$3,$4,$5::jsonb)', [root, node, id(971), 'progress', terms]);
  check(submitted.state, 'pending', 'Contributor submission remains pending');
  await db.exec('reset role');
  const pendingNotice = (await db.query("select * from notifications where task_id=$1 and entity_type='m7_work_proposal' and type='approval_needed'", [root])).rows;
  check(pendingNotice.length, 1, 'One canonical notification for a pending review');
  check([pendingNotice[0].user_id, pendingNotice[0].title, pendingNotice[0].task_title, pendingNotice[0].reason], [id(6), 'Your review is needed', 'Service delivery', 'Called the venue to confirm access'], 'Assigned reviewer gets personal, specific wording and the work note');
  check(pendingNotice[0].message.includes('Confirm service venue'), true, 'Review alert identifies the exact subtask');
  await actor(9);
  await value('select m7_propose_work($1,$2,$3,$4,$5::jsonb)', [root, node, id(971), 'progress', terms]);
  await db.exec('reset role');
  check(await value("select count(*) from notifications where task_id=$1 and entity_type='m7_work_proposal' and type='approval_needed'", [root]), 1, 'Retrying the same submission does not duplicate alerts');
  await actor(6);
  await value('select m7_decide_work($1,$2,false,$3)', [id(971), id(972), 'Confirm the accessible entrance before proceeding']);
  await db.exec('reset role');
  const decision = (await db.query("select * from notifications where task_id=$1 and entity_type='m7_work_proposal' and type='status_change'", [root])).rows[0];
  check([decision.user_id, decision.status_to, decision.reason], [id(9), 'changes_requested', 'Confirm the accessible entrance before proceeding'], 'Decision notification includes reviewer feedback and the correct recipient');
  check(decision.message.includes('Confirm service venue') && !decision.title.includes('complete'), true, 'Returned work is not described as completed');
  await actor(6);
  await value('select m7_decide_work($1,$2,false,$3)', [id(971), id(972), 'Confirm the accessible entrance before proceeding']);
  await db.exec('reset role');
  check(await value("select count(*) from notifications where task_id=$1 and entity_type='m7_work_proposal' and type='status_change'", [root]), 1, 'Retrying a decision does not duplicate alerts');
  await actor(5);
  await value('select submit_task_progress($1,null,null,null,null,$2,null,null)', [root, 'Spoke with the service team']);
  await db.exec('reset role');
  const updates = (await db.query("select * from notifications where task_id=$1 and title='Task work updated'", [root])).rows;
  check(updates.map(row => row.user_id).sort(), [2, 6, 9].map(id).sort(), 'Task updates reach the relevant team and supervisors without self-alerts');
  check(updates.every(row => row.reason === 'Spoke with the service team' && row.entity_type === 'work_change'), true, 'Work note stays readable and uses the work-change destination');
  await actor(6);
  await value("select save_subtask_work_update($1,'in_progress',null,$2,null,null,null)", [node, 'Venue entrance checked']);
  await db.exec('reset role');
  const childUpdates = (await db.query("select * from notifications where work_node_id=$1 and title='Subtask work updated'", [node])).rows;
  check(new Set(childUpdates.map(row => row.user_id)).size, childUpdates.length, 'Existing reviewer alert and added team alerts do not duplicate recipients');
  check(childUpdates.some(row => row.user_id === id(9)) && childUpdates.some(row => row.user_id === id(2)), true, 'Subtask teammate and Office Head learn about work updates');
  await actor(5);
  const tree = () => value('select r7_work_tree($1)', [root]);
  const planned = id(980);
  await value('select r7_work_command($1,$2,$3,$4,$5::jsonb)', [root, (await tree()).revision, id(981), 'create', JSON.stringify({ id: planned, title: 'Plan transport', lead: id(6), people: [id(6), id(9)], start: '2030-01-01', due: '2030-12-19', standalone: true })]);
  const editPayload = JSON.stringify({ id: planned, title: 'Arrange transport', start: '2030-01-01', due: '2030-12-18', standalone: true, note: 'Venue needs an earlier delivery' });
  const revision = (await tree()).revision;
  const impact = await value('select nw_work_impact($1,$2,$3,$4::jsonb)', [root, revision, 'edit', editPayload]);
  const edited = await value('select nw_work_command($1,$2,$3,$4,$5::jsonb,$6)', [root, revision, id(982), 'edit', editPayload, impact.fingerprint]);
  check(edited.nodes.find(item => item.id === planned).title, 'Arrange transport', 'Planning change uses the guarded, confirmed command');
  await db.exec('reset role');
  const changes = (await db.query("select * from notifications where work_node_id=$1 and title='Subtask details changed'", [planned])).rows;
  check(changes.map(row => row.user_id).sort(), [2, 6, 9].map(id).sort(), 'Final nested edit notifies each involved recipient once');
  check(changes.every(row => row.reason.includes('Title: Plan transport → Arrange transport') && row.reason.includes('2030-12-19 → 2030-12-18')), true, 'Nested edit includes exact changed values');
  await actor(5);
  await value('select nw_work_command($1,$2,$3,$4,$5::jsonb,$6)', [root, revision, id(982), 'edit', editPayload, impact.fingerprint]);
  await db.exec('reset role');
  check(await value("select count(*) from notifications where work_node_id=$1 and title='Subtask details changed'", [planned]), 3, 'Retrying an edited plan does not duplicate alerts');
  await actor(5);
  const deletion = JSON.stringify({ id: planned });
  const deleteRevision = (await tree()).revision;
  const deleteImpact = await value('select nw_work_impact($1,$2,$3,$4::jsonb)', [root, deleteRevision, 'delete', deletion]);
  await value('select nw_work_command($1,$2,$3,$4,$5::jsonb,$6)', [root, deleteRevision, id(983), 'delete', deletion, deleteImpact.fingerprint]);
  await db.exec('reset role');
  const removals = (await db.query("select * from notifications where task_id=$1 and title='Subtask removed'", [root])).rows;
  check(removals.length, 3, 'Removal alerts retain the accessible task entrance');
  check(removals.every(row => row.work_node_id === null && row.message.includes('Arrange transport')), true, 'Removed subtask notification does not link to a deleted item');
  // Real private-draft creation and edit: no operational recipient should be alerted.
  await actor(2);
  const draft = await value('select (create_project_draft_once($1::jsonb,$2)).id', [JSON.stringify({ title: 'Unpublished work', org_id: office, owner_id: id(2), status: 'planning' }), id(975)]);
  const version = await value('select updated_at::text from projects where id=$1', [draft]);
  await value('select save_project_definition($1,$2::jsonb)', [draft, JSON.stringify({ title: 'Unpublished work', description: 'Private details', scope: 'Private services', lead: id(6), start: '2026-10-01', end: '2030-12-31', noFunding: true, version })]);
  await value('select finish_project_setup($1)', [draft]);
  const group = await value('select id from project_groups where project_id=$1 and is_default', [draft]);
  const hidden = await value('select (m7_draft_task_create($1,$2,$3)).id', [draft, group, 'Private planning task']);
  await db.query("update tasks set title='Private planning revised' where id=$1", [hidden]);
  await db.exec('reset role');
  check(await value('select count(*) from notifications where task_id=$1', [hidden]), 0, 'Private planning edits stay private');
  console.log(`Work notifications: ${assertions} PostgreSQL assertions passed (disposable database; no hosted writes).`);
} finally { await db.close(); }
